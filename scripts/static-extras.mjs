/**
 * After `STATIC=1 next build`, writes what a static host needs and Next cannot emit:
 * out/_headers for security and caching, and out/_redirects for the canonical host.
 */
import { copyFileSync, existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";

const OUT = "out";
if (!existsSync(OUT)) {
  console.error("No out/ directory. Run: npm run build:static");
  process.exit(1);
}

// Next writes the social image without an extension, which a static host would serve as a download.
// Keep a .png copy and force the type on the extensionless path that the meta tag points at.
if (existsSync(`${OUT}/opengraph-image`)) copyFileSync(`${OUT}/opengraph-image`, `${OUT}/opengraph-image.png`);

writeFileSync(`${OUT}/_headers`, `# generated by scripts/static-extras.mjs
/opengraph-image
  Content-Type: image/png
  Cache-Control: public, max-age=86400

/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: SAMEORIGIN
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  Strict-Transport-Security: max-age=63072000; includeSubDomains

/_next/static/*
  Cache-Control: public, max-age=31536000, immutable

/sw.js
  Cache-Control: no-cache
  Service-Worker-Allowed: /

/manifest.webmanifest
  Content-Type: application/manifest+json
  Cache-Control: public, max-age=3600
`);

/**
 * No _redirects file is written. Cloudflare's asset server only accepts relative rules there, and
 * an absolute one is skipped silently, so sending www to the apex belongs in a Redirect Rule in
 * the Cloudflare dashboard instead.
 */

/**
 * The service worker is stamped with this build's id, which is what makes its caches new. Without
 * it a visitor would keep last week's files for ever, and an update nobody receives is not one.
 */
const buildId = (() => {
  try {
    return readdirSync(`${OUT}/_next/static`).find((name) => !["chunks", "css", "media"].includes(name)) ?? String(Date.now());
  } catch {
    return String(Date.now());
  }
})();

if (existsSync(`${OUT}/sw.js`)) {
  const sw = readFileSync(`${OUT}/sw.js`, "utf8").replace('const VERSION = "dev";', `const VERSION = ${JSON.stringify(buildId)};`);
  writeFileSync(`${OUT}/sw.js`, sw);
  console.log(`Stamped out/sw.js with build ${buildId}`);
}

console.log("Wrote out/_headers");
